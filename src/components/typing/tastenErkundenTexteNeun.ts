    tippFinden: `${t.fin}: ${t.wasFin} (Alt + 4 ${t.wechselt})`,
    beendet: t.beendet,
    zurueck: t.zurueck,
    zurueckWin: `${t.win} ${t.zurueck}`,
    zurueckDruck: `${t.druck} ${t.zurueck}`,
    tastaturHinweis: t.tastaturHinweis,
    belegung: t.belegung,
    belegungMac: t.belegungMac,
    melden: t.melden,
    fensterName: t.erk,
    titel: t.erk,
    modus: t.modus,
    erkunden: t.erk,
    finden: t.fin,
    beenden: t.beenden,
    alleGefunden: t.alleGefunden,
    tasteVon: t.tasteVon,
    drueck: t.drueck,
    nochEinmal: t.nochEinmal,
    auswahl: t.auswahl,
    meine: t.meine,
    alle: t.alle,
    zuAlle: `${t.alle}: Alt + 5.`,
    zuMeine: `${t.meine}: Alt + 5.`,
    tippMeine: `${t.meine}: ${t.wasMeine} (Alt + 5 ${t.wechselt})`,
